/**
 * Readiness verdict for the claims linter (F-WEBINSTALL-FLASHALL-CLAIM-LINT,
 * D-015).
 *
 * The linter's readiness family (`no-readiness-overclaim`) is suppressed only
 * when the machine readiness verdict is PASS. This module is the ONE place that
 * verdict is derived, so the linter and the (Backend-lane) readiness gate read
 * the SAME shipped facts — acceptance criterion (e).
 *
 * Two inputs, in precedence order:
 *
 *   1. An explicit verdict file (`--readiness-verdict=<path>`), JSON
 *      `{ "gate": "PASS" | "FAIL" | ... }`. This is the transport by which the
 *      Backend lane's `readiness-gate` hands its single exit code to the
 *      linter without either lane importing the other (file-ownership
 *      boundary). A file that is absent/unparseable/a non-PASS token does NOT
 *      pass — FAIL CLOSED.
 *   2. Derivation from the shipped product facts, when no file is given —
 *      MIRRORING the Backend lane's `scripts/readiness-gate.mjs` clauses so the
 *      two cannot disagree on the same tree:
 *      - `status.json`: the honesty guard (`flashCapability.liveFlashClaimed`
 *        must not be `true` — claiming a live flash with no hardware is the
 *        overclaim; a `false` flag is the honest state, NOT a blocker).
 *      - `docs/flash-matrix.json` (generated by the Backend lane): every
 *        advertised product must have a packed, COMPLETE channel, every packed
 *        channel's `sourceStamp` must equal its advertised current stamp
 *        (freshness), and every packed device's current stamp must resolve.
 *
 * Readiness is "advertised ⟺ packed and fresh", NOT "these images boot" and NOT
 * "the alpha posture is over". The alpha/`preLaunch` posture is separate
 * policy; conflating it with readiness was an early draft error corrected here
 * once the gate's contract landed (acceptance (e): the gate reads the same
 * source the copy does — and so does this).
 *
 * Absent both, the verdict is NOT-ready. This never fabricates a PASS: a PASS
 * requires positive, present evidence on every clause.
 *
 * HONESTY: this is a claim-discipline input, not a boot or flash proof.
 * `BOOT_VERIFIED=false` and it does not touch `LIVE_FLASH_CLAIMED`.
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
// The ONE authoritative readiness evaluator (T-WEBINSTALL-READINESS-RULE-SINGLE-SOURCE).
import { evaluateGate } from "../../scripts/readiness-gate.mjs";

export interface ReadinessVerdict {
  /** True only when every readiness clause passed on present evidence. */
  readonly ready: boolean;
  /** Human-readable account of how the verdict was reached (for evidence). */
  readonly reasons: readonly string[];
  /** Where the verdict came from. */
  readonly source: "explicit-file" | "derived" | "none";
}

const INSTALLER_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(path, "utf8")) as unknown;
}

/** Load the matrix, or `null` when absent (the gate fails closed on `null`). */
function readMatrixOrNull(path: string): Record<string, unknown> | null {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8")) as Record<string, unknown>;
  } catch {
    return null;
  }
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  return typeof value === "object" && value !== null ? (value as Record<string, unknown>) : undefined;
}

/**
 * Read an explicit verdict file written by the readiness gate. Returns
 * `undefined` (so the caller falls back to derivation) only when no path was
 * given. A path that was given but is unreadable/malformed/non-PASS yields a
 * NOT-ready verdict — never a silent fallthrough to a PASS.
 */
export function verdictFromFile(path: string): ReadinessVerdict {
  if (!existsSync(path)) {
    return { ready: false, reasons: [`readiness verdict file not found: ${path}`], source: "explicit-file" };
  }
  let parsed: Record<string, unknown> | undefined;
  try {
    parsed = asRecord(readJson(path));
  } catch (err) {
    return {
      ready: false,
      reasons: [`readiness verdict file is not JSON: ${path} (${err instanceof Error ? err.message : "parse error"})`],
      source: "explicit-file",
    };
  }
  const gate = parsed?.gate;
  if (gate === "PASS") {
    return { ready: true, reasons: [`readiness gate reports PASS (${path})`], source: "explicit-file" };
  }
  return {
    ready: false,
    reasons: [`readiness gate does not report PASS: ${JSON.stringify(gate ?? null)} (${path})`],
    source: "explicit-file",
  };
}

/**
 * Derive the verdict from the shipped facts. Every clause must pass on present
 * evidence; a missing or malformed input is a NOT-ready reason, never a pass.
 */
export function deriveReadinessVerdict(installerRoot: string = INSTALLER_ROOT): ReadinessVerdict {
  // T-WEBINSTALL-READINESS-RULE-SINGLE-SOURCE: this used to re-derive the gate's
  // clauses inline (and drifted — it never inspected `bootVerified`, never
  // checked the trust anchor, and compared `sourceStamp`/`currentStamp` by hand).
  // It now DELEGATES to the one authoritative evaluator, so the linter and the
  // gate cannot disagree: the linter is exactly as strict as the gate, including
  // the tree-binding and trust-anchor clauses. The gate fails closed on a
  // missing matrix, so there is no path to a fabricated PASS here.
  const reasons: string[] = [];

  // Honesty guard sourced from `status.json` (the live product facts). The gate
  // checks the matrix's mirrored `honesty` block; this checks the origin, so a
  // live-flash claim blocks readiness even when no matrix has been generated.
  const statusPath = join(installerRoot, "status.json");
  if (!existsSync(statusPath)) {
    reasons.push(`status.json missing at ${statusPath}`);
  } else {
    const status = asRecord(readJson(statusPath));
    const flashCapability = asRecord(status?.flashCapability);
    if (flashCapability?.liveFlashClaimed === true) {
      reasons.push("status.json flashCapability.liveFlashClaimed=true — a live flash is claimed");
    }
  }

  let evaluation: { pass: boolean; clauses: { id: string; ok: boolean; detail: string }[] };
  try {
    evaluation = evaluateGate(readMatrixOrNull(join(installerRoot, "docs", "flash-matrix.json")), {
      installerRoot,
    });
  } catch (error) {
    // Fail closed: an evaluator that cannot run never yields a PASS.
    return {
      ready: false,
      reasons: [...reasons, `readiness gate could not evaluate the tree: ${String(error)}`],
      source: "derived",
    };
  }

  for (const clause of evaluation.clauses) {
    if (!clause.ok) {
      reasons.push(`${clause.id}: ${clause.detail}`);
    }
  }

  return { ready: reasons.length === 0, reasons, source: "derived" };
}

/**
 * Resolve the verdict with the precedence in the module docstring. `explicit`
 * is the `--readiness-verdict=` value (or undefined).
 */
export function resolveReadinessVerdict(
  explicit: string | undefined,
  installerRoot: string = INSTALLER_ROOT,
): ReadinessVerdict {
  if (explicit !== undefined && explicit.length > 0) {
    return verdictFromFile(explicit);
  }
  try {
    return deriveReadinessVerdict(installerRoot);
  } catch (err) {
    return {
      ready: false,
      reasons: [`readiness derivation failed: ${err instanceof Error ? err.message : "unknown error"}`],
      source: "derived",
    };
  }
}
