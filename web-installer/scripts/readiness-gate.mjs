#!/usr/bin/env node
/**
 * readiness-gate.mjs — ONE command, ONE exit code, for flash readiness.
 *
 * T-WEBINSTALL-FLASHALL-READINESS-GATE (original) +
 * T-WEBINSTALL-READINESS-GATE-TREE-BINDING (this revision).
 *
 * OBJETIVO: turn "the installer is ready to flash what it advertises" into a
 * single deterministic PASS/FAIL verdict that is bound to LIVE TREE REALITY,
 * not to a generated document's claims.
 *
 *   node scripts/readiness-gate.mjs                    # gate the live tree
 *   node scripts/readiness-gate.mjs --matrix=PATH      # gate a given matrix
 *   node scripts/readiness-gate.mjs --json             # machine-readable output
 *   node scripts/readiness-gate.mjs --verdict-out=PATH # write {gate:PASS|FAIL}
 *
 * EXIT CODES
 *   0  PASS  — every gate clause held
 *   1  FAIL  — at least one clause failed (the reason is printed)
 *   2  ERROR — the gate could not evaluate (missing/unparseable input) — FAIL
 *              CLOSED: an unevaluable gate is never a pass.
 *
 * SUBSTRATE: THE FILESYSTEM, NOT THE MATRIX
 *   `docs/flash-matrix.json` is a *convenience projection* generated by
 *   `scripts/gen-flash-matrix.mjs`. It is NOT the source of truth, and this
 *   gate no longer trusts it as one. At gate time the gate probes the tree
 *   directly (via `scripts/tree-probe.mjs`):
 *     - `channels/<product>/` exists and holds manifest.json, files.txt,
 *       SHA256SUMS and avb_pkmd.bin;
 *     - the `<product>-latest` pointer is re-resolved from
 *       `releases/desktop-flash/` and the channel's freshness is recomputed
 *       from the FILESYSTEM — never from the matrix's `currentStamp` /
 *       `stampsOnDisk` fields;
 *     - `counts.packedChannels` is reconciled against the set actually
 *       verified on disk.
 *   When the matrix and the tree disagree in any way, **the tree wins and the
 *   gate FAILS**. (The pre-fix gate read exactly one file and printed PASS for
 *   a tree that could flash nothing.)
 *
 * THE FRESHNESS RULE IS NOT RE-IMPLEMENTED HERE. `checkChannelFreshness` in
 * `scripts/channel-freshness.mjs` is the one predicate; this gate only feeds it
 * values read from disk before and after probing.
 *
 * SUMMARY ⇔ EXIT EQUIVALENCE (no DEC-ARCH-027 divergence): the word printed on
 * stdout (`READINESS-GATE: PASS|FAIL`) and the exit code are computed from the
 * SAME `clauses` array in one expression. There is no second code path that
 * could print PASS while exiting non-zero, or vice versa.
 *
 * CLAUSES (each independently fails)
 *   1. matrix present + schemaVersion 1
 *   2. every ALLOWED_PRODUCTS device has a packed channel (advertised == packed)
 *   3. every packed channel is complete: ≥1 artifact, no unmapped artifact,
 *      each artifact's files.txt phase equals its declared phase
 *   4. no packed channel is missing its current stamp
 *   5. every packed channel's sourceStamp EQUALS its advertised current stamp
 *   6. honesty flags are not claiming a live flash
 *  12. (trust-anchor) every packed channel's `avb_pkmd.bin` matches its
 *      OUT-OF-BAND pin in `docs/expected-anchors.json`
 *      (T-WEBINSTALL-TRUST-ANCHOR-VERIFICATION): the shipped digest must equal
 *      a checked-in, review-gated constant that is NOT derived from the
 *      channels. Without it, a forgery that replaces the anchor AND rewrites
 *      the channel metadata to match is self-consistent and passes every other
 *      clause. The rule lives in `scripts/trust-anchor.mjs`; the gate only
 *      feeds it digits read from disk + the pin document.
 *   7. (tree) every channel the matrix calls packed exists on disk with its four
 *      required files
 *   8. (tree) every packed product's `<product>-latest` pointer resolves on disk
 *      and its channel is fresh BY THE FILESYSTEM
 *   9. (tree) `counts.packedChannels` equals the set actually verified on disk
 *  10. (tree) every packed device in the matrix matches the channel dir on disk
 *      (the projection agrees with reality)
 *  11. (stability) the probed files did not change identity during the gate
 *
 * Clauses 1–6 are unchanged from the original gate; they are evaluated against
 * the matrix, but clauses 5–6 in particular can no longer pass on a stale
 * document's say-so because clauses 7–10 now cross-check the same documents
 * against the tree.
 *
 * SIDE-EFFECT FREE by default: the only write is `--verdict-out`. The gate can
 * be run from any cwd — `INSTALLER_ROOT` is derived from `import.meta.url`.
 *
 * HONESTY: BOOT_VERIFIED=false. A PASS means "advertised ⟺ packed and fresh
 * ON DISK AND IN THE MATRIX", never "these images boot". It does not touch
 * LIVE_FLASH_CLAIMED.
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildMatrix, INSTALLER_ROOT, RELEASES_ROOT, readAllowedProducts } from "./gen-flash-matrix.mjs";
import { checkChannelFreshness, freshnessClause } from "./channel-freshness.mjs";
import {
  ANCHOR_FILE,
  checkTrustAnchors,
  loadAnchorPinsFromText,
} from "./trust-anchor.mjs";
import {
  fileIdentity,
  listChannelDirs,
  listStampsOnDisk,
  makeRoots,
  probeChannel,
  readManifestClaim,
  resolveLatestPointer,
  REQUIRED_CHANNEL_FILES,
} from "./tree-probe.mjs";

const DEFAULT_MATRIX = join(INSTALLER_ROOT, "docs", "flash-matrix.json");
const STATUS_PATH = join(INSTALLER_ROOT, "status.json");
const DEFAULT_RELEASES_DIR = RELEASES_ROOT;

/** One clause's outcome. `ok:false` fails the whole gate. */
function clause(id, description, ok, detail) {
  return { id, description, ok, detail };
}

/**
 * Probe the live tree ONCE and remember the identity of every file the verdict
 * depends on, so a concurrent writer cannot swap bytes underneath the gate.
 */
function probeTree(installerRoot, releasesDir, products) {
  const roots = makeRoots(installerRoot, releasesDir);
  const channels = new Map();
  const pointers = new Map();
  for (const product of products) {
    channels.set(product, probeChannel(roots, product));
    pointers.set(product, resolveLatestPointer(roots, product));
  }
  const identities = new Map();
  for (const product of products) {
    const dir = join(roots.channelsRoot, product);
    for (const name of REQUIRED_CHANNEL_FILES) {
      identities.set(join(dir, name), fileIdentity(join(dir, name)));
    }
    identities.set(
      join(releasesDir, `${product}-latest`),
      fileIdentity(join(releasesDir, `${product}-latest`)),
    );
  }
  return {
    roots,
    channels,
    pointers,
    identities,
    channelDirsOnDisk: listChannelDirs(roots),
    stampsOnDisk: new Map(products.map((p) => [p, listStampsOnDisk(roots, p)])),
  };
}

/**
 * Evaluate every readiness clause against a matrix object AND the tree it
 * describes.
 *
 * `options.installerRoot` / `options.releasesDir` let a drill point the probe
 * at a throwaway /tmp tree; they default to this module's installer root and
 * the repo's releases dir.
 */
export function evaluateGate(matrix, options = {}) {
  const allowed = options.allowedProducts ?? readAllowedProducts().products;
  // Default to the installer root this module lives in, NOT process.cwd(): the
  // gate must probe the same tree regardless of where it is invoked from.
  const installerRoot = options.installerRoot ?? INSTALLER_ROOT;
  const releasesDir = options.releasesDir ?? DEFAULT_RELEASES_DIR;
  const clauses = [];

  // --- Clause 1: the matrix is present and well-formed --------------------
  const wellFormed =
    matrix !== null &&
    typeof matrix === "object" &&
    matrix.schemaVersion === 1 &&
    Array.isArray(matrix.devices) &&
    Array.isArray(matrix.divergence);
  clauses.push(
    clause(
      "matrix-present",
      "flash-matrix.json present and schemaVersion 1",
      wellFormed,
      wellFormed ? "ok" : "matrix is missing, malformed, or an unexpected schemaVersion",
    ),
  );
  if (!wellFormed) {
    // Fail closed: with no matrix we cannot check anything else.
    return { pass: false, clauses };
  }

  const devices = matrix.devices;
  const byProduct = new Map(devices.map((d) => [d.product, d]));

  // --- Clause 2: advertised == packed -------------------------------------
  const advertisedNotPacked = [];
  for (const product of allowed) {
    const device = byProduct.get(product);
    if (device === undefined || device.packed !== true) {
      advertisedNotPacked.push(product);
    }
  }
  clauses.push(
    clause(
      "advertised-equals-packed",
      "every advertised product has a packed channel",
      advertisedNotPacked.length === 0,
      advertisedNotPacked.length === 0
        ? "all advertised products are packed"
        : `advertised but not packed: ${advertisedNotPacked.join(", ")}`,
    ),
  );

  // --- The tree probe (one snapshot, reused by every tree clause) ---------
  const matrixProducts = devices.map((d) => String(d.product));
  const snap = probeTree(installerRoot, releasesDir, matrixProducts);

  // --- Clause 3: completeness (no stub, no unmapped artifact) -------------
  const incomplete = [];
  for (const device of devices) {
    if (device.packed !== true) continue;
    const channels = device.channels ?? [];
    if (channels.length === 0) {
      incomplete.push(`${device.product} is marked packed but has no channel`);
      continue;
    }
    for (const channel of channels) {
      if (!Array.isArray(channel.artifacts) || channel.artifacts.length === 0) {
        incomplete.push(`${device.product} channel lists no artifacts (stub)`);
        continue;
      }
      if ((channel.unmappedArtifacts ?? []).length > 0) {
        incomplete.push(
          `${device.product} has unmapped artifacts: ${(channel.unmappedArtifacts ?? []).join(", ")}`,
        );
      }
      for (const artifact of channel.artifacts) {
        if (artifact.phaseMatches !== true || artifact.inManifest !== true) {
          incomplete.push(`${device.product}/${artifact.name} phase or manifest mapping is inconsistent`);
        }
      }
    }
  }
  clauses.push(
    clause(
      "channel-completeness",
      "every packed channel has ≥1 fully-mapped artifact (never a stub)",
      incomplete.length === 0,
      incomplete.length === 0 ? "all packed channels are complete" : incomplete.join("; "),
    ),
  );

  // --- Clause 4: no packed channel is missing its current stamp -----------
  const missingStamp = [];
  for (const device of devices) {
    if (device.packed !== true) continue;
    if (device.currentStamp === null || device.currentStamp === undefined) {
      missingStamp.push(device.product);
    }
  }
  clauses.push(
    clause(
      "current-stamp-resolvable",
      "every packed channel resolves to a current stamp on disk",
      missingStamp.length === 0,
      missingStamp.length === 0 ? "all current stamps resolve" : `unresolvable: ${missingStamp.join(", ")}`,
    ),
  );

  // --- Clause 5: freshness against DISK-derived values (tree wins) --------
  // For each packed device the gate compares TWO freshness results:
  //   (i)  the matrix's own projection (sourceStamp/currentStamp/stampsOnDisk
  //        as the document states them), and
  //   (ii) the disk-derived reality: the channel's manifest.json CLAIM, the
  //        `<product>-latest` pointer re-resolved from releases/, and the stamp
  //        dirs actually present.
  // The clause fails if either is stale, or if the two disagree. The invariant
  // itself is `checkChannelFreshness` — imported, never re-implemented.
  const freshnessResults = [];
  const disagreement = [];
  for (const device of devices) {
    if (device.packed !== true) continue;
    const product = String(device.product);
    const channelProbe = snap.channels.get(product) ?? null;
    const onDisk = snap.stampsOnDisk.get(product) ?? [];
    const latest = snap.pointers.get(product) ?? null;
    const diskClaim = channelProbe === null ? null : readManifestClaim(channelProbe);

    // The channel to test on disk: the manifest actually present. When a matrix
    // channel row exists, union the two so a mismatch is visible rather than
    // silently dropped.
    const matrixChannels = device.channels ?? [];
    const diskStamp = diskClaim?.sourceStamp ?? null;
    const matrixStamps = matrixChannels.map((c) => c.sourceStamp);
    const allStamps = [...new Set([...matrixStamps, ...(diskStamp === null ? [] : [diskStamp])])];

    // Disk-derived current stamp: what <product>-latest ACTUALLY points at.
    const diskCurrent = latest?.target ?? null;

    // (i) the matrix's own projection — always evaluated, so a contradicting
    // matrix is caught even when the tree behind it is fine.
    for (const channel of matrixChannels) {
      freshnessResults.push(
        checkChannelFreshness(product, {
          sourceStamp: channel.sourceStamp,
          releaseId: channel.releaseId,
          unixEpoch: channel.unixEpoch,
          currentStamp: typeof device.currentStamp === "string" ? device.currentStamp : null,
          stampsOnDisk: Array.isArray(device.stampsOnDisk) ? device.stampsOnDisk : [],
        }),
      );
    }

    // (ii) disk-derived reality.
    for (const stamp of allStamps) {
      freshnessResults.push(
        checkChannelFreshness(product, {
          sourceStamp: stamp,
          releaseId: diskStamp === stamp ? (diskClaim?.releaseId ?? null) : (matrixChannels.find((c) => c.sourceStamp === stamp)?.releaseId ?? null),
          unixEpoch: diskStamp === stamp ? (diskClaim?.unixEpoch ?? null) : (matrixChannels.find((c) => c.sourceStamp === stamp)?.unixEpoch ?? null),
          currentStamp: diskCurrent,
          stampsOnDisk: onDisk,
        }),
      );
    }

    // Matrix ⇔ tree reconciliation of the pointer and the stamp set.
    const matrixCurrent = typeof device.currentStamp === "string" ? device.currentStamp : null;
    if (matrixCurrent !== diskCurrent) {
      disagreement.push(`${product}: matrix currentStamp ${matrixCurrent ?? "(none)"} vs disk pointer ${diskCurrent ?? "(none)"}`);
    }
    const matrixSet = [...new Set(Array.isArray(device.stampsOnDisk) ? device.stampsOnDisk : [])].sort();
    const diskSet = [...onDisk].sort();
    if (matrixSet.length !== diskSet.length || matrixSet.some((s, i) => s !== diskSet[i])) {
      const onlyMatrix = matrixSet.filter((s) => !diskSet.includes(s));
      const onlyDisk = diskSet.filter((s) => !matrixSet.includes(s));
      const bits = [];
      if (onlyMatrix.length > 0) bits.push(`matrix-only: ${onlyMatrix.join(", ")}`);
      if (onlyDisk.length > 0) bits.push(`disk-only: ${onlyDisk.join(", ")}`);
      disagreement.push(`${product}: stampsOnDisk differs (${bits.join("; ")})`);
    }
    if (diskStamp !== null && matrixStamps.length > 0 && !matrixStamps.includes(diskStamp)) {
      disagreement.push(
        `${product}: manifest on disk says ${diskStamp} but the matrix claims ${matrixStamps.join(", ")}`,
      );
    }
  }
  const freshness = freshnessClause(freshnessResults);
  clauses.push(freshness);
  clauses.push(
    clause(
      "tree-freshness",
      "the matrix's currentStamp/stampsOnDisk agree with the pointer + stamps on disk",
      disagreement.length === 0,
      disagreement.length === 0
        ? "matrix projection agrees with the filesystem"
        : disagreedText(disagreement),
    ),
  );

  // --- Clause 6: honesty flags ------------------------------------------
  const honesty = matrix.honesty ?? {};
  const honestyOk = honesty.liveFlashClaimed !== true && honesty.bootVerified === false;
  clauses.push(
    clause(
      "honesty-flags",
      "matrix does not claim a live flash or boot verification",
      honestyOk,
      honestyOk
        ? "LIVE_FLASH_CLAIMED=false, BOOT_VERIFIED=false"
        : `liveFlashClaimed=${String(honesty.liveFlashClaimed)}, bootVerified=${String(honesty.bootVerified)}`,
    ),
  );

  // --- Clauses 7-11: the tree itself --------------------------------------
  const packedDevices = devices.filter((d) => d.packed === true);

  // Clause 7: the channel dir exists with its four required files.
  const missingOnDisk = [];
  for (const device of packedDevices) {
    const p = snap.channels.get(String(device.product));
    if (p === undefined) continue;
    if (!p.exists) {
      missingOnDisk.push(`${device.product}: channels/${device.product}/ does not exist on disk`);
    } else if (p.missingFiles.length > 0) {
      missingOnDisk.push(`${device.product}: missing ${p.missingFiles.join(", ")}`);
    }
  }
  clauses.push(
    clause(
      "channels-on-disk",
      "every channel the matrix calls packed exists on disk with manifest.json, files.txt, SHA256SUMS, avb_pkmd.bin",
      missingOnDisk.length === 0,
      missingOnDisk.length === 0
        ? `all ${String(packedDevices.length)} matrix-packed channel(s) present on disk`
        : missingOnDisk.join("; "),
    ),
  );

  // Clause 8: the <product>-latest pointer resolves on disk, and the channel
  // is fresh per the DISK-resolved pointer (not the matrix's claim).
  const pointerProblems = [];
  for (const device of packedDevices) {
    const product = String(device.product);
    const pointer = snap.pointers.get(product);
    if (pointer === undefined) continue;
    if (!pointer.present) {
      pointerProblems.push(`${product}: releases/desktop-flash/${product}-latest is absent`);
    } else if (pointer.target === null) {
      pointerProblems.push(`${product}: ${pointer.name} does not resolve (${pointer.error ?? "no target"})`);
    } else if (!pointer.targetExists) {
      pointerProblems.push(`${product}: ${pointer.name} -> ${pointer.target}, which is not a stamp dir on disk`);
    }
    const claim = snap.channels.get(product);
    const diskClaim = claim === undefined ? null : readManifestClaim(claim);
    if (diskClaim !== null && !diskClaim.ok) {
      pointerProblems.push(`${product}: ${diskClaim.error ?? "manifest claim unreadable"}`);
    } else if (diskClaim !== null && pointer.target !== null && diskClaim.sourceStamp !== pointer.target) {
      pointerProblems.push(
        `${product}: packed from ${diskClaim.sourceStamp} but <product>-latest points at ${pointer.target} — STALE`,
      );
    }
  }
  clauses.push(
    clause(
      "latest-pointer-on-disk",
      "every packed product's <product>-latest resolves on disk and names the stamp the channel was packed from",
      pointerProblems.length === 0,
      pointerProblems.length === 0
        ? `all ${String(packedDevices.length)} pointer(s) resolve and match`
        : pointerProblems.join("; "),
    ),
  );

  // Clause 9: counts.packedChannels reconciled against the set ACTUALLY
  // verified on disk (no packed=99, no packed=0-with-devices).
  const verifiedOnDisk = snap.channelDirsOnDisk.filter((p) => {
    const cp = snap.channels.get(p) ?? probeChannel(snap.roots, p);
    return cp.packed;
  });
  const claimed = matrix.counts?.packedChannels;
  const countOk = typeof claimed === "number" && claimed === verifiedOnDisk.length;
  clauses.push(
    clause(
      "packed-count-reconciled",
      "counts.packedChannels equals the packed channels actually verified on disk",
      countOk,
      countOk
        ? `${String(verifiedOnDisk.length)} packed channel(s) verified on disk`
        : `matrix claims packedChannels=${String(claimed)} but ${String(verifiedOnDisk.length)} packed channel(s) are verified on disk (${verifiedOnDisk.join(", ") || "none"})`,
    ),
  );

  // Clause 10: the matrix's per-device packed flag agrees with the disk.
  const projectionDrift = [];
  for (const device of packedDevices) {
    const product = String(device.product);
    const cp = snap.channels.get(product);
    if (cp === undefined) continue;
    if (!cp.packed) {
      projectionDrift.push(`${product}: matrix says packed, disk says ${cp.exists ? "incomplete channel" : "no channel dir"}`);
      continue;
    }
    if (device.packedDir !== undefined && device.packedDir !== null && device.packedDir !== cp.dir) {
      projectionDrift.push(`${product}: matrix packedDir ${String(device.packedDir)} != ${cp.dir}`);
    }
    const row = (device.channels ?? [])[0];
    if (row !== undefined) {
      const claim = readManifestClaim(cp);
      if (claim.ok && row.sourceStamp !== claim.sourceStamp) {
        projectionDrift.push(
          `${product}: matrix sourceStamp ${String(row.sourceStamp)} != manifest.json on disk ${String(claim.sourceStamp)}`,
        );
      }
      if (claim.ok && row.releaseId !== undefined && row.releaseId !== claim.releaseId) {
        projectionDrift.push(
          `${product}: matrix releaseId ${String(row.releaseId)} != manifest.json on disk ${String(claim.releaseId)}`,
        );
      }
    }
  }
  clauses.push(
    clause(
      "matrix-matches-disk",
      "every device the matrix calls packed matches the channel + manifest on disk",
      projectionDrift.length === 0,
      projectionDrift.length === 0 ? "matrix projection matches the channel dirs" : projectionDrift.join("; "),
    ),
  );

  // Clause 11: nothing the verdict depended on swapped under us.
  const moved = [];
  for (const [path, before] of snap.identities) {
    const after = fileIdentity(path);
    if (before === null && after === null) continue;
    if (before === null || after === null) {
      moved.push(`${path} appeared/disappeared during the gate`);
      continue;
    }
    if (
      before.ino !== after.ino ||
      before.size !== after.size ||
      before.mtimeMs !== after.mtimeMs ||
      before.link !== after.link
    ) {
      moved.push(`${path} changed during the gate`);
    }
  }
  clauses.push(
    clause(
      "tree-stable",
      "the channel files + pointers the gate probed did not change during the gate",
      moved.length === 0,
      moved.length === 0 ? "no probed file changed identity" : moved.join("; "),
    ),
  );

  // --- Clause 12: the AVB trust anchor matches its OUT-OF-BAND pin ---------
  // T-WEBINSTALL-TRUST-ANCHOR-VERIFICATION. Reads `avb_pkmd.bin` from DISK for
  // every packed channel and compares it to the checked-in pin. The matrix is
  // not consulted: its digest is derived from the channel's own metadata (via
  // SHA256SUMS), which is exactly the evidence a forger can rewrite.
  clauses.push(trustAnchorClause(snap, installerRoot, options));
  clauses.push(channelShapeClause(snap, installerRoot, options));

  return { pass: clauses.every((c) => c.ok), clauses };
}

/**
 * Clause 12. Fails closed when the pin file is missing/unparseable, when a
 * packed channel has no pin, or when any digest/size differs. `options.pins`
 * (parsed) and `options.anchorsPath` let the tests inject a fixture.
 */
function trustAnchorClause(snap, installerRoot, options) {
  if (snap === null) {
    return clause(
      "trust-anchor",
      "every packed channel's avb_pkmd.bin matches the out-of-band pin",
      false,
      "tree probing was skipped — the AVB trust anchor cannot be verified (fail closed)",
    );
  }
  const anchorsPath = options.anchorsPath ?? join(installerRoot, "docs", "expected-anchors.json");
  const pins =
    options.pins ?? loadAnchorPinsFromText(anchorsPath, existsSync(anchorsPath) ? readFileSync(anchorsPath, "utf8") : null);
  const observed = new Map();
  for (const product of snap.channels.keys()) {
    const path = join(snap.roots.channelsRoot, product, ANCHOR_FILE);
    let digest = null;
    let size = null;
    if (existsSync(path)) {
      try {
        digest = createHash("sha256").update(readFileSync(path)).digest("hex");
        size = statSync(path).size;
      } catch {
        digest = null;
        size = null;
      }
    }
    observed.set(product, { sha256: digest, size });
  }
  const result = checkTrustAnchors(observed, pins);
  return clause(
    "trust-anchor",
    "every packed channel's avb_pkmd.bin matches the out-of-band pin in docs/expected-anchors.json",
    result.ok,
    result.detail,
  );
}

/** Keep multiline detail readable when many reconciliations fail at once. */
function disagreedText(parts) {
  return parts.length <= 4 ? parts.join("; ") : `${parts.slice(0, 4).join("; ")} (+${String(parts.length - 4)} more)`;
}

/**
 * Clause 13 — per-device channel SHAPE
 * (T-WEBINSTALL-RANGO-ARTIFACT-SHAPE-DIVERGENCE).
 *
 * Sibling channels (tokay/akita/komodo) publish 19 artifacts and no `super.img`;
 * rango publishes 21 including a populated `super.img` and a device-specific
 * `vbmeta_valid_flags3.img`. That divergence is a REAL device difference, not
 * padding — but "verifies green while bound to a structurally different artifact
 * set" is how a wrong pack slips through. So the expected shape is pinned
 * per device in `docs/expected-shape.json` and asserted here: a pack that gains,
 * loses, or swaps an artifact FAILS rather than verifying green.
 *
 * Fail closed: a missing/unparseable pins file, or a product with no expectation,
 * FAILS — an unasserted shape is not a verified shape.
 */
function channelShapeClause(snap, installerRoot, options) {
  const id = "channel-shape";
  const description = "every packed channel publishes exactly its per-device artifact set (docs/expected-shape.json)";
  if (snap === null) {
    return clause(id, description, false, "tree probing was skipped — channel shape cannot be verified (fail closed)");
  }
  const shapePath = options.shapePath ?? join(installerRoot, "docs", "expected-shape.json");
  let pins = options.shapePins ?? null;
  if (pins === null) {
    if (!existsSync(shapePath)) {
      return clause(id, description, false, `${shapePath} is absent — an unasserted shape is not a verified shape (fail closed)`);
    }
    try {
      pins = JSON.parse(readFileSync(shapePath, "utf8"));
    } catch {
      return clause(id, description, false, `${shapePath} is unparseable — fail closed`);
    }
  }
  const expectedDevices = pins?.devices;
  if (expectedDevices === null || typeof expectedDevices !== "object") {
    return clause(id, description, false, `${shapePath} has no devices map — fail closed`);
  }

  const problems = [];
  for (const [product, probed] of snap.channels) {
    if (probed?.packed !== true) continue;
    const expected = expectedDevices[product];
    if (expected === undefined) {
      problems.push(`${product}: packed but has no pinned expected shape`);
      continue;
    }
    const artifacts = probed.manifest?.artifacts;
    if (!Array.isArray(artifacts)) {
      problems.push(`${product}: manifest declares no artifacts array`);
      continue;
    }
    const actual = artifacts.map((a) => String(a?.name)).sort();
    const want = Array.isArray(expected.artifacts) ? [...expected.artifacts].map(String).sort() : null;
    if (want === null) {
      problems.push(`${product}: pinned shape lists no artifacts`);
      continue;
    }
    const gained = actual.filter((n) => !want.includes(n));
    const lost = want.filter((n) => !actual.includes(n));
    if (gained.length > 0) problems.push(`${product}: unexpected artifact(s): ${gained.join(", ")}`);
    if (lost.length > 0) problems.push(`${product}: missing pinned artifact(s): ${lost.join(", ")}`);
    if (typeof expected.artifactCount === "number" && expected.artifactCount !== actual.length) {
      problems.push(`${product}: artifactCount ${String(actual.length)} != pinned ${String(expected.artifactCount)}`);
    }
  }

  return clause(
    id,
    description,
    problems.length === 0,
    problems.length === 0
      ? `all ${String([...snap.channels.values()].filter((c) => c?.packed === true).length)} packed channel(s) match their pinned shape`
      : disagreedText(problems),
  );
}

/* ------------------------------------------------------------------ CLI --- */

function loadMatrix(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function summarize(matrix) {
  if (matrix === null) return "no matrix";
  const stale = (matrix.summary ?? {}).staleChannels ?? [];
  const notPacked = (matrix.summary ?? {}).advertisedNotPacked ?? [];
  return `packed=${String(matrix.counts?.packedChannels ?? "?")} advertised-not-packed=${String(
    notPacked.length,
  )} stale=${String(stale.length)}`;
}

export function runGate(argv) {
  const matrixArg = argv.find((a) => a.startsWith("--matrix="));
  const verdictArg = argv.find((a) => a.startsWith("--verdict-out="));
  const installArg = argv.find((a) => a.startsWith("--installer-root="));
  const releasesArg = argv.find((a) => a.startsWith("--releases-dir="));
  const json = argv.includes("--json");

  // DRILL SUPPORT (tests + /tmp reproduction): point the tree probe at another
  // installer root / releases dir. Precedence: CLI flag > env var > derived
  // default (INSTALLER_ROOT from import.meta.url, so any cwd works). A real
  // repo never sets either.
  const installerRoot =
    installArg !== undefined
      ? installArg.slice("--installer-root=".length)
      : (process.env.GUARDTALK_INSTALLER_ROOT ?? INSTALLER_ROOT);
  const releasesDir =
    releasesArg !== undefined
      ? releasesArg.slice("--releases-dir=".length)
      : (process.env.GUARDTALK_RELEASES_DIR ?? DEFAULT_RELEASES_DIR);

  // The matrix default follows the EFFECTIVE root, never the gate's own install
  // path. Resolving it against INSTALLER_ROOT while probing a drill root would
  // read the REAL repo's matrix and print PASS for a tree with no channels —
  // the exact vacuity this gate exists to catch (INCIDENT 2026-10-18T12:13).
  const matrixPath =
    matrixArg !== undefined
      ? matrixArg.slice("--matrix=".length)
      : join(installerRoot, "docs", "flash-matrix.json");

  const matrix = loadMatrix(matrixPath);
  // ERROR (exit 2) when the input cannot be evaluated — fail closed.
  const errored = matrix === null;
  const result = errored
    ? { pass: false, clauses: [] }
    : evaluateGate(matrix, { installerRoot, releasesDir });
  // ONE expression drives BOTH the exit code and the printed word.
  const pass = !errored && result.pass;
  const exitCode = errored ? 2 : pass ? 0 : 1;
  const word = errored ? "ERROR" : pass ? "PASS" : "FAIL";

  const failed = result.clauses.filter((c) => !c.ok).map((c) => c.id);
  const summary = summarize(matrix);

  if (json) {
    process.stdout.write(
      `${JSON.stringify(
        {
          gate: word,
          exitCode,
          matrix: matrixPath,
          installerRoot,
          releasesDir,
          summary,
          clauses: result.clauses,
        },
        null,
        2,
      )}\n`,
    );
  } else {
    for (const c of result.clauses) {
      process.stdout.write(`  [${c.ok ? "ok" : "NO"}] ${c.id}: ${c.detail}\n`);
    }
    if (errored) {
      process.stdout.write(`  [NO] matrix-loadable: cannot read ${matrixPath} — fail closed\n`);
    }
    process.stdout.write(
      `READINESS-GATE: ${word} (exit ${String(exitCode)}) · ${summary} · ${matrixPath}\n`,
    );
  }

  // The linter's transport (D-015): a { gate: PASS|FAIL } file. Written only
  // when asked, so the gate stays side-effect-free by default.
  if (verdictArg !== undefined) {
    const out = verdictArg.slice("--verdict-out=".length);
    writeFileSync(
      out,
      `${JSON.stringify(
        {
          gate: word,
          $comment:
            "Written by scripts/readiness-gate.mjs. Consumed by lib/claims/lint-claims.ts via --readiness-verdict. Regenerate; do not hand-edit.",
          matrix: matrixPath,
          installerRoot,
          summary,
          failedClauses: failed,
        },
        null,
        2,
      )}\n`,
    );
  }
  return exitCode;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exitCode = runGate(process.argv.slice(2));
}

