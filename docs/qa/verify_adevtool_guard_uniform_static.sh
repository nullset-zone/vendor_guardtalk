#!/usr/bin/env bash
# =============================================================================
# T-DEVICE-ALIGN-RANGO-GUARD-FIX — adevtool version-guard FLEET-UNIFORMITY gate
# Decision: DEC-DEVICE-ALIGN-021   (finding: DEC-DEVICE-ALIGN-019)
# =============================================================================
# Every `vendor/google_devices/<dev>/adevtool-version-check.mk` is a generated
# guard that aborts the build when the pinned `vendor/adevtool` commit drifts.
# The fleet must be UNIFORMLY fail-closed: `$(error`, never `$(warning`.
#
# WHY THIS GATE EXISTS (the durability half of the fix):
#   These 14 files are GENERATED by adevtool. A hand edit is silently reverted
#   by the next regeneration, so a fix that is only a hand edit can evaporate
#   without anyone noticing. The provenance of `$(warning` is mechanical:
#
#     vendor/adevtool/src/blobs/build.ts:38   writeVersionCheckFile(..., warnOnly = false)
#     vendor/adevtool/src/blobs/build.ts:45   $(warnOnly ? 'warning' : 'error')
#     vendor/adevtool/src/commands/generate-all.ts:326  writeVersionCheckFile(..., flags.noVerify)
#
#   So `--no-verify` => warnOnly=true => `$(warning` is the FINGERPRINT of an
#   unverified regeneration, not a sanctioned design choice. `rango` carried
#   that fingerprint while being the device ADVERTISED as the experimental one.
#
# RESYNC RULE (resync rule: what to do when this gate fails after a regeneration):
#   regenerate with `adevtool generate-all -d <dev>` WITHOUT `--no-verify`.
#   Never `--no-verify`. If a guard comes back as `$(warning`, the regeneration
#   was unverified: discard it and re-run with verification enabled.
#
# NON-VACUITY (DEC-DEVICE-ALIGN-012): a gate that cannot be shown to fail is
# decoration. `--self-test` builds a sandbox, proves the CLEAN sandbox PASSES
# (positive control) and that flipping ONE device back to `$(warning` makes the
# gate exit non-zero (injection), echoing the observed FAIL lines verbatim.
#
# Modes:
#   (default)     assert the live tree
#   --self-test   prove this gate FAILS on injection + PASSES on a clean sandbox
#   --help
#
# Env:
#   GT_AGUARD_ROOT   override the root to inspect (used by --self-test sandboxes)
#
# Scope note: pin-vs-live-HEAD equality is deliberately NOT asserted here. That
# is a drift condition an operator changes on purpose; this gate owns fleet
# UNIFORMITY only. The live check is `git -C vendor/adevtool rev-parse HEAD`
# vs the pinned commit reported below.
#
# Usage (from GrapheneOS-worktree root):
#   bash vendor/guardtalk/docs/qa/verify_adevtool_guard_uniform_static.sh; echo $?
#   bash vendor/guardtalk/docs/qa/verify_adevtool_guard_uniform_static.sh --self-test; echo $?
#
# Exit: 0 = all clauses hold. non-zero = at least one clause violated / no fleet.
# =============================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../../.." && pwd)"
SELF="$ROOT/vendor/guardtalk/docs/qa/verify_adevtool_guard_uniform_static.sh"

# The fleet size is an ASSERTION, not a discovery: a glob that silently matches
# fewer files must fail loudly rather than "pass on 3 files".
EXPECTED_N=14
GUARD_REL='vendor/google_devices/*/adevtool-version-check.mk'

FAIL=0
PASS_N=0
pass(){ echo "PASS: $*"; PASS_N=$((PASS_N+1)); }
fail(){ echo "FAIL: $*"; FAIL=1; }

# --- helpers -----------------------------------------------------------------
# Fixed-string counting (grep -oF). Deliberate: `\$(error` is NOT a safe ERE
# (`(` opens a group -> "Unmatched ("), which is the exact quoting class that
# produced a vacuous check earlier this wave (DEC-DEVICE-ALIGN-012 #3).
count_fixed(){ # <file> <literal>
  local c
  c="$(grep -oF -- "$2" "$1" 2>/dev/null | wc -l)"
  printf '%s' "${c//[^0-9]/}"
}

run_checks(){ # <root>
  local root="$1" n=0 f dev err warn pins="" pin0="" pin_bad=""
  local -a files=()

  cd "$root" || { fail "cannot cd to root '$root'"; return 1; }

  # C01/C02 — fleet discovery is non-vacuous in BOTH directions.
  shopt -s nullglob
  files=( $GUARD_REL )
  shopt -u nullglob
  n=${#files[@]}
  if [[ "$n" -gt 0 ]]; then
    pass "C01 fleet discovered: ${n} guard file(s) matched"
  else
    fail "C01 fleet EMPTY: 0 guard files matched '$GUARD_REL' (a loop over nothing 'passes')"
  fi
  if [[ "$n" -eq "$EXPECTED_N" ]]; then
    pass "C02 fleet size == ${EXPECTED_N} (guard fleet complete, none missing/renamed)"
  else
    fail "C02 fleet size ${n} != expected ${EXPECTED_N} — a device was added/removed/renamed"
  fi
  [[ "$n" -eq 0 ]] && return 1

  # C03/C04 — per-guard exactly one directive, never both, never neither; zero warnings.
  for f in "${files[@]}"; do
    dev="$(basename "$(dirname "$f")")"
    err="$(count_fixed "$f" '$(error')"
    warn="$(count_fixed "$f" '$(warning')"
    if [[ $((err + warn)) -eq 1 ]]; then
      pass "C03 ${dev}: exactly one directive (error=${err} warning=${warn})"
    else
      fail "C03 ${dev}: expected exactly 1 of \$(error/\$(warning, found error=${err} warning=${warn}"
    fi
    if [[ "$warn" -eq 0 ]]; then
      pass "C04 ${dev}: fail-closed (\$(warning count 0)"
    else
      fail "C04 ${dev}: uses \$(warning x${warn} — ADVISORY guard, an unverified-regeneration fingerprint (--no-verify)"
    fi

    # C05 — pin uniformity: every guard must pin the same 40-hex commit.
    local p
    p="$(grep -oE '[0-9a-f]{40}' "$f" 2>/dev/null | head -1)"
    if [[ -z "$p" ]]; then
      pin_bad="$pin_bad ${dev}(none)"
    elif [[ -z "$pin0" ]]; then
      pin0="$p"; pins="$p"
    elif [[ "$p" != "$pin0" ]]; then
      pin_bad="$pin_bad ${dev}($p)"
    fi

    # C06 — the guard's own remediation text must not recommend the degrading flag.
    if [[ "$(count_fixed "$f" '--no-verify')" -eq 0 ]]; then
      pass "C06 ${dev}: remediation text does not recommend --no-verify"
    else
      fail "C06 ${dev}: guard text recommends --no-verify (it would produce \$(warning itself)"
    fi
  done

  if [[ -z "$pin0" ]]; then
    fail "C05 pin uniformity: no 40-hex commit pin found in any guard"
  elif [[ -z "$pin_bad" ]]; then
    pass "C05 pin uniformity: all ${n} guards pin the identical commit ${pin0}"
  else
    fail "C05 pin uniformity: divergent pins — baseline ${pin0}, offenders:${pin_bad}"
  fi
}

# C07 — the provenance/resync comment this fix must carry, asserted over itself
# so it cannot be stripped without the gate noticing.
check_provenance(){
  local miss=""
  grep -qF -- 'T-DEVICE-ALIGN-RANGO-GUARD-FIX' "$SELF" || miss="$miss T-DEVICE-ALIGN-RANGO-GUARD-FIX"
  grep -qF -- 'DEC-DEVICE-ALIGN-021'            "$SELF" || miss="$miss DEC-DEVICE-ALIGN-021"
  grep -qi -- 'without .*--no-verify'           "$SELF" || miss="$miss resync-rule(without --no-verify)"
  grep -qF -- 'generate-all -d <dev>'           "$SELF" || miss="$miss resync-rule(generate-all -d <dev>)"
  if [[ -z "$miss" ]]; then
    pass "C07 provenance comment present: task id + DEC-DEVICE-ALIGN-021 + resync rule (regenerate with 'adevtool generate-all -d <dev>' without --no-verify)"
  else
    fail "C07 provenance comment INCOMPLETE — missing:${miss}"
  fi
}

# --- self-test: prove this gate can FAIL -------------------------------------
self_test(){
  local sb rc_pos rc_neg verdict=0
  sb="$(mktemp -d "${TMPDIR:-/tmp}/aguard-selftest.XXXXXX")" || return 1
  trap 'rm -rf "$sb"' RETURN

  mkdir -p "$sb/vendor/google_devices"
  local f d
  for f in "$ROOT"/$GUARD_REL; do
    d="$(basename "$(dirname "$f")")"
    mkdir -p "$sb/vendor/google_devices/$d"
    cp "$f" "$sb/vendor/google_devices/$d/"
  done
  echo "sandbox: $sb"
  echo "sandbox guards: $(ls -1 "$sb"/$GUARD_REL 2>/dev/null | wc -l)"

  # POSITIVE CONTROL: a clean copy must PASS.
  GT_AGUARD_ROOT="$sb" bash "$SELF" >"$sb/pos.log" 2>&1
  rc_pos=$?
  echo "[positive control] clean sandbox rc=${rc_pos} (expect 0)"
  if [[ "$rc_pos" -ne 0 ]]; then
    verdict=1
    echo "[positive control] UNEXPECTED FAIL — the gate rejects a clean fleet; PASS/FAIL would be meaningless:"
    grep -E '^(FAIL|RESULT)' "$sb/pos.log" || true
  fi

  # INJECTION: flip one real device back to $(warning — the gate MUST fail.
  sed -i 's/\$(error/\$(warning/' "$sb/vendor/google_devices/rango/adevtool-version-check.mk"
  echo "[injection] rango guard flipped back to \$(warning:"
  grep -n 'warning' "$sb/vendor/google_devices/rango/adevtool-version-check.mk"
  GT_AGUARD_ROOT="$sb" bash "$SELF" >"$sb/neg.log" 2>&1
  rc_neg=$?
  echo "[injection] injected sandbox rc=${rc_neg} (expect non-zero)"
  echo "[injection] observed gate verdict, verbatim:"
  grep -E '^(FAIL|RESULT|PASS=(.*))|PASS=' "$sb/neg.log" || echo "(no FAIL lines — gate did NOT detect the injection)"
  if [[ "$rc_neg" -eq 0 ]]; then
    verdict=1
    echo "[injection] VACUOUS: the gate PASSED a fleet containing \$(warning"
  fi
  if ! grep -q 'C04 rango:' "$sb/neg.log"; then
    verdict=1
    echo "[injection] VACUOUS: rc was non-zero but not via the C04 warning clause"
  fi

  rm -rf "$sb"
  trap - RETURN
  if [[ "$verdict" -eq 0 ]]; then
    echo "SELFTEST: PASS — gate FAILS on an injected \$(warning and PASSES on a clean sandbox"
    return 0
  fi
  echo "SELFTEST: FAIL — non-vacuity NOT established"
  return 1
}

# --- main --------------------------------------------------------------------
case "${1:-}" in
  --help|-h) sed -n '2,66p' "$0"; exit 0 ;;
  --self-test) self_test; exit $? ;;
  "") ;;
  *) echo "unknown argument: $1 (try --help)" >&2; exit 2 ;;
esac

TARGET="${GT_AGUARD_ROOT:-$ROOT}"
echo "==================================================================="
echo "T-DEVICE-ALIGN-RANGO-GUARD-FIX — adevtool guard fleet uniformity"
echo "root=$TARGET"
echo "expected guards=$EXPECTED_N  pattern=$GUARD_REL"
echo "==================================================================="

run_checks "$TARGET"
check_provenance

echo "-------------------------------------------------------------------"
if [[ "$FAIL" -ne 0 ]]; then
  echo "RESULT: FAIL — the guard fleet is NOT uniformly fail-closed"
  echo "PASS=$PASS_N"
  exit 1
fi
echo "RESULT: PASS — ${EXPECTED_N}/${EXPECTED_N} guards are uniformly fail-closed (\$(error only)"
echo "PASS=$PASS_N"
exit 0
